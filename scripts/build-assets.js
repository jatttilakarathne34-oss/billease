'use strict';
// Packs the web pages (public/) into assets.js so the server can serve them itself on any host,
// even if the host does not publish the public/ folder. Safe: does nothing if public/index.html is missing.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..', 'public');
if (!fs.existsSync(path.join(root, 'index.html'))) { console.log('build-assets: public/index.html not found, keeping existing assets.js'); process.exit(0); }
const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8' };
const out = {};
(function walk(dir) { for (const f of fs.readdirSync(dir)) { const full = path.join(dir, f), st = fs.statSync(full); if (st.isDirectory()) walk(full); else if (TYPES[path.extname(f)]) out['/' + path.relative(root, full).split(path.sep).join('/')] = { type: TYPES[path.extname(f)], body: fs.readFileSync(full, 'utf8') }; } })(root);
fs.writeFileSync(path.join(__dirname, '..', 'assets.js'), '// GENERATED by scripts/build-assets.js — do not edit\nmodule.exports = ' + JSON.stringify(out) + ';\n');
console.log('build-assets: packed', Object.keys(out).join(', '));
